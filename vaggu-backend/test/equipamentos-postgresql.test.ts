import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import request from 'supertest';
import { prepararBancoDeTeste } from '../test-support/banco-de-teste.js';
import { createEquipamentosService } from '../src/equipamentos/service.js';
import { createTelemetriaService } from '../src/telemetria/service.js';
import { expirarSensores } from '../src/telemetria/expiracao.js';
import { createApp } from '../src/app.js';
const url = process.env.TEST_DATABASE_URL;
test('equipamentos isolam vínculo, segredo, manutenção, comunicação e rotação', { skip: url ? false : 'Configure TEST_DATABASE_URL.' }, async t => {
 const prisma = await prepararBancoDeTeste(t, url!);
 const shopping = await prisma.shopping.create({ data: { nome: 'Equipamentos' } });
 const outro = await prisma.shopping.create({ data: { nome: 'Outro' } });
 const andar = await prisma.andar.create({ data: { shoppingId: shopping.id, nome: 'G1', ordem: 1 } });
 const setor = await prisma.setor.create({ data: { shoppingId: shopping.id, andarId: andar.id, nome: 'A' } });
 const vaga = await prisma.vaga.create({ data: { shoppingId: shopping.id, andarId: andar.id, setorId: setor.id, codigo: 'A01' } });
 const vagaAlheia = await prisma.vaga.create({ data: { shoppingId: outro.id, codigo: 'X' } });
 const servico = createEquipamentosService(prisma), autor = randomUUID();
 for (const codigo of ['-P1', '_P1', 'Sensor 1', 'sensór']) await assert.rejects(servico.criarPlaca(shopping.id, { codigo, nome: 'Inválida' }), /Comece com/);
 const { placa, chave } = await servico.criarPlaca(shopping.id, { codigo: 'PLACA-TESTE', nome: 'Teste' });
 await assert.rejects(servico.vincularSensor(shopping.id, placa.id, { codigo: 'Sensor 1', vagaId: vaga.id }), /Comece com/);
 await assert.rejects(servico.vincularSensor(shopping.id, placa.id, { codigo: 'S0', vagaId: vagaAlheia.id }), /Vaga ativa não encontrada/);
 const { sensor } = await servico.vincularSensor(shopping.id, placa.id, { codigo: 'S1', vagaId: vaga.id });
 await assert.rejects(servico.vincularSensor(shopping.id, placa.id, { codigo: 'S2', vagaId: vaga.id }), /já vinculados/);
 const listado = JSON.stringify(await servico.listar(shopping.id));
 assert.equal(listado.includes(chave), false); assert.equal(listado.includes('chaveApiHash'), false);
 await assert.rejects(servico.rotacionarChave(outro.id, placa.id), /Placa não encontrada/);
 const config = { lacunaMaximaMs: 15_000, timeoutSensorMs: 120_000, timeoutPlacaMs: 120_000 };
 let agora = new Date(); let sequencia = 0;
 const telemetria = createTelemetriaService(prisma, config, { now: () => agora });
 const ler = () => telemetria.receberEstados(`Device ${chave}`, { placaCodigo: placa.codigo, inicializacaoId: 'ensaio-local', sequencia: sequencia++, leituras: [{ sensorCodigo: sensor.codigo, estadoDetectado: 'LIVRE' }] });
 for (let i = 0; i < 3; i++) { await ler(); agora = new Date(agora.getTime() + 15_000); }
 assert.equal((await prisma.vaga.findUniqueOrThrow({ where: { id: vaga.id } })).estadoAtual, 'LIVRE');
 const manutencao = await servico.abrirManutencao(shopping.id, placa.id, { motivo: 'Troca do sensor', sensorId: sensor.id }, autor);
 await servico.abrirManutencao(shopping.id, placa.id, { motivo: 'Duplicada', sensorId: sensor.id }, autor);
 assert.equal(await prisma.ocorrenciaEquipamento.count({ where: { tipo: 'MANUTENCAO', encerradaEm: null } }), 1);
 await prisma.ocorrenciaEquipamento.createMany({ data: Array.from({ length: 101 }, () => ({ shoppingId: shopping.id, dispositivoId: placa.id, tipo: 'MANUTENCAO', motivo: 'Histórico concluído', encerradaEm: new Date() })) });
 assert.ok((await servico.listar(shopping.id)).ocorrencias.some(o => o.id === manutencao.ocorrencia.id));
 await ler();
 assert.equal((await prisma.vaga.findUniqueOrThrow({ where: { id: vaga.id } })).estadoAtual, 'INDISPONIVEL');
 assert.equal((await prisma.ocorrenciaEquipamento.findUniqueOrThrow({ where: { id: manutencao.ocorrencia.id } })).encerradaEm, null);
 await servico.encerrarManutencao(shopping.id, manutencao.ocorrencia.id, { conclusao: 'Sensor conferido' }, autor);
 await ler();
 assert.equal((await prisma.vaga.findUniqueOrThrow({ where: { id: vaga.id } })).estadoAtual, 'INDISPONIVEL');
 agora = new Date(agora.getTime() + 15_000); await ler(); agora = new Date(agora.getTime() + 15_000); await ler();
 assert.equal((await prisma.vaga.findUniqueOrThrow({ where: { id: vaga.id } })).estadoAtual, 'LIVRE');
 agora = new Date(agora.getTime() + 130_000);
 await expirarSensores(prisma, config, agora); await expirarSensores(prisma, config, agora);
 assert.equal(await prisma.ocorrenciaEquipamento.count({ where: { tipo: 'COMUNICACAO', encerradaEm: null } }), 1);
 assert.equal((await prisma.vaga.findUniqueOrThrow({ where: { id: vaga.id } })).estadoAtual, 'INDISPONIVEL');
 await telemetria.receberHeartbeat(`Device ${chave}`, { placaCodigo: placa.codigo, inicializacaoId: 'ensaio-local', sequencia: sequencia++ });
 assert.equal(await prisma.ocorrenciaEquipamento.count({ where: { tipo: 'COMUNICACAO', sensorId: null, encerradaEm: null } }), 0);
 assert.equal((await prisma.vaga.findUniqueOrThrow({ where: { id: vaga.id } })).estadoAtual, 'INDISPONIVEL');
 const nova = await servico.rotacionarChave(shopping.id, placa.id);
 await assert.rejects(ler(), /Credencial/);
 await telemetria.receberHeartbeat(`Device ${nova.chave}`, { placaCodigo: placa.codigo, inicializacaoId: 'ensaio-local', sequencia: sequencia++ });
 const auth = { authenticate: async () => ({ usuario: { id: autor, perfil: 'SHOPPING', shoppingId: shopping.id, trocarSenhaObrigatoria: false } }) };
 const app = createApp({ checkDatabase: () => 1, auth, equipamentos: servico, telemetria });
 await request(app).post(`/api/v1/shoppings/${shopping.id}/equipamentos`).send({ nome: 'Não permitido', codigo: 'X' }).expect(403);
 await request(app).get('/api/v1/estacionamento/ocorrencias').expect(200);
 await request(app).post('/api/v1/telemetria/heartbeat').set('Authorization', `Device ${nova.chave}`).send({ placaCodigo: placa.codigo, inicializacaoId: 'ensaio-local', sequencia: sequencia++ }).expect(202);
});
